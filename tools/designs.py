"""九个板块的「具体设计」。

回答第三个问题：**这个最先进的方法，具体怎么设计？**
每个板块给出：

    headline  设计目标（一句话）
    specs[]   关键设计参数：k=参数 v=取值 n=为什么是这个值
    subs[]    设计分解：t=子系统 n=做什么 / 关键指标
    scene()   三维等轴测图（tools/iso.py 生成内联 SVG）
    caption   图的说明（放 <figcaption>，不要画进 SVG）
    note      设计说明（取舍、口径、不确定性）

画图约定（改图前先读）：
    - 坐标：x 向右下 30°、y 向左下 30°、z 竖直向上，单位是「设计单位」。
    - **引线标注一律往屏幕水平方向延伸**：用 R(d, z) 取右侧锚点、L(d, z) 取左侧锚点。
      文字宽度会参与 auto_fit，往竖直方向拉长会把整图压小。
    - 不要在图里放长句说明（会被裁），长句一律放 caption。
    - 半透明材质用 HULL（舱体剖面）或 Iso(..., 'rgba(...)') 传入的三元组。
"""

from iso import Iso, INK, MUTED, FAINT

HULL = ('rgba(242,243,245,.45)', 'rgba(217,220,225,.38)', 'rgba(196,200,207,.34)')


def R(d, z):
    """屏幕右侧的标注锚点。"""
    return (d, -d, z)


def L(d, z):
    """屏幕左侧的标注锚点。"""
    return (-d, d, z)


# 屏幕水平位移的换算式：u = (x - y) * cos30，v = (x + y) * sin30 - z。
# 要让锚点相对物体在屏幕上「纯水平」移动 d（不改变高度），需要
#     Δx = d / cos30，Δz = d * tan30（右）；左则改 Δy。
# 下面两个助手按物体自身坐标算锚点，比手填 R()/L() 更不容易撞上别的物体。
_K = 1 / 0.8660254      # ≈ 1.1547
_T = 0.5 / 0.8660254    # ≈ 0.5774


def roff(p, d):
    """物体 p 的屏幕右侧 d 个设计单位处（高度不变）。"""
    x, y, z = p
    return (x + d * _K, y, z + d * _T)


def loff(p, d):
    """物体 p 的屏幕左侧 d 个设计单位处（高度不变）。"""
    x, y, z = p
    return (x, y + d * _K, z + d * _T)


