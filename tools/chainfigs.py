# ---------------------------------------------------------------- 三个小工具
def _flow(steps, notes=()):
    """四格主线。标题 ≤ 7 字、副标题 ≤ 11 字。"""
    d = Dia(680, 158 + len(notes) * 22)
    d.flow(46, steps, 24, 632, 54)
    for i, t in enumerate(notes):
        d.annot(24, 152 + i * 22, t, FAINT)
    return d


def _bars(items, notes=()):
    """横条对比。items = [(标签, 值文字, 0..1, 色键, 说明)]"""
    last = 34 + (len(items) - 1) * 52 + 26
    first = last + 26
    d = Dia(680, first + len(notes) * 22 + 6)
    d.hbars(30, 34, 620, list(items), row=52, bar=14)
    for i, t in enumerate(notes):
        d.annot(30, first + i * 22, t, FAINT)
    return d


def _series(xlabels, ylabels, lines, xname, yname, ymax, notes=()):
    """折线。notes 放在坐标轴下方（series 的 xname 在 y0+h+30，说明要从 +48 起）。"""
    d = Dia(680, 246 + len(notes) * 22)
    d.series(92, 46, 532, 134, xlabels, ylabels, lines,
             xname=xname, yname=yname, ymax=ymax)
    for i, t in enumerate(notes):
        d.annot(92, 240 + i * 22, t, FAINT)
    return d


def _scatter(pts, xlab, ylab, quad=None, notes=()):
    """两维权衡。pts = [(x, y, 标签, 色键)]，归一化 0..1"""
    d = Dia(680, 246 + len(notes) * 22)
    d.scatter(104, 42, 496, 190, list(pts), xlab, ylab, quad=quad)
    for i, t in enumerate(notes):
        d.annot(104, 260 + i * 22, t, FAINT)
    return d


