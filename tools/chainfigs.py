"""技术链路 54 环的配图：每一环一张「这一环在做什么 / 为什么难」。

定位与技术路线层（`techfigs.py`）不同，两层不要画同一件事：
    techfigs   回答「这一步怎么推进」——从今天的基线到目标状态，是纵向的路径
    chainfigs  回答「这一环现在是什么样、卡在哪」——是横向的现状切片

写作要求是**通俗易懂**（用户原话）：
    - 一图只讲一个信息点，优先用进度、对比、流程这类不需要背景知识的形式；
    - 图注不假设读者懂专业词，第一次出现的概念就地解释（如「入轨的门槛是速度」）；
    - 能给出数字就给数字（40%、92.3%、98%），数字比形容词可信。

图注编号用「链路图 1..6」，是层内序号——与技术路线层（无编号）、
创业者路线图（理论图 1..6）、板块开头（导览图 1..2）都区分开。
"""

