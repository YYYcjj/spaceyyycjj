# ------------------------------------------------------------------ 3D 辅助
def roff(p, d):
    """从物体坐标 p 往屏幕右侧取锚点（等轴测里靠增大 x−y 实现）。"""
    x, y, z = p
    return (x + d, y - d, z)


def loff(p, d):
    """从物体坐标 p 往屏幕左侧取锚点。"""
    x, y, z = p
    return (x - d, y + d, z)


