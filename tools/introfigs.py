"""每个板块开头两张「导览图」——给第一次接触这个领域的人。

九个板块用**同一套框架**，这是刻意的：读者读完第一个板块，
就学会了怎么读后面八个。两张图各自回答一个问题：

    图 1  这个领域在解决什么问题     —— 一条主线链（flow）
    图 2  现在走到哪一步了           —— 三档进展（layers）

图 2 的三档沿用全站正文的写作框架：**已经做到的 / 正在验证的 / 还只在纸上的**。
对新人来说这是最有用的一张图——它一眼分清「什么可以信、什么别信」。

写作口径（与正文一致，但更平实）：
    - 句子短，不用缩写；专业词第一次出现时就地解释，不假设读者懂。
    - 不写「持续推进」「赋能」这类空话；每一格都要能给读者一个具体印象。
    - 图 2 的三档必须各举一个可核对的实例，不能只写状态词。
"""

