# ---------------------------------------------------------------- 两个小工具
def _flow_fig(steps, note_lines=()):
    """图 1：一条主线。steps = [(标题, 副标题, 色键)]，标题 ≤ 7 字、副标题 ≤ 10 字。"""
    d = Dia(680, 158 + len(note_lines) * 22)
    d.flow(46, steps, 24, 632, 54)
    for i, t in enumerate(note_lines):
        d.annot(24, 152 + i * 22, t, FAINT)
    return d


def _step_fig(items):
    """图 2：三档进展。items = [(档名, 一句标签, 色键, 具体实例)]"""
    d = Dia(680, 244)
    d.layers(40, 46, 600, list(items), row=54, thick=26)
    return d


def _bars_fig(items, note_lines=()):
    """成熟度横条：用于「前提还差多远」这类判断。items = [(项, 状态, 0..1, 色键, 说明)]

    说明行的基准不能写死——它取决于项数（每项占 row 高，最后一项的 note 在 y+26）。
    """
    last_note = 34 + (len(items) - 1) * 52 + 26
    first = last_note + 26
    d = Dia(680, first + len(note_lines) * 22 + 6)
    d.hbars(30, 34, 620, list(items), row=52, bar=14)
    for i, t in enumerate(note_lines):
        d.annot(30, first + i * 22, t, FAINT)
    return d


