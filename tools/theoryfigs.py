"""创业者路线图的「理论图」。

每个板块 6 张：**赛道判断 1 张 + 五个阶段各 1 张**（9 × 6 = 54 张）。
回答的是「为什么这样成立」——机制、权衡、依赖、时机，而不是「长什么样」
（那是 designs.py / iso.py 的活）。

形式选择：
    数值关系、权衡、累积 → series / scatter / hbars
    时序、窗口、阶段     → timeline / flow
    结构占比             → stack / layers

版式规矩同 dia.py（画布 680 宽、留白宁多勿少、文字必须显式给色）。
图注**不画进 SVG**，放在 <figcaption> 里，编号用层内序号「理论图 1..6」——
刻意避开「图 01」（具体设计）与「图 10.1」（收口页）这两套编号，防止读者混淆。
"""

