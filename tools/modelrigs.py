def rig_html(slug, idx=0):
    """渲染一个模型 + 编号图例。"""
    spec = RIGS[slug][idx]
    return spec['build']().html() + legend_html(spec['legend'])


def check():
    """构建期自检：所有模型的编号点不重叠、几何体不出框。"""
    bad = []
    for slug, specs in RIGS.items():
        for i, spec in enumerate(specs):
            g = spec['build']()
            bad += g.problems()
    return bad


if __name__ == '__main__':
    total = 0
    for slug, specs in RIGS.items():
        for i, spec in enumerate(specs):
            g = spec['build']()
            g.k = g._fit()
            n = sum(len(p['faces']) for p in g._parts)
            total += n
            print(f'  {slug:<12} #{i}  {spec["title"]:<26} '
                  f'部件 {len(g._parts):>2} 面片 {n:>3} 编号点 {len(g._pins)}')
    print(f'\n  面片合计 {total}')
    probs = check()
    for p in probs:
        print('  BAD ' + p)
    print('\n' + ('全部通过' if not probs else f'{len(probs)} 处不通过'))
