def _ship_body(g, gap=0.0):
    """总装与分解图共用同一套舱段几何，只差段间距（gap）。

    两处写两遍迟早会漂移——而且这两张图并排放在同一页上，一漂移就会被看出来。
    """
    R = 15.0
    # (底半径, 高度, 颜色, 环缝周期) 自下而上：越靠下越重、越少人待
    segs = [
        (R, 20, 'dark', 3.6),      # ① 推进级
        (R, 48, 'steel', 7.0),     # ② 推进剂贮箱
        (R, 26, 'gray', 6.2),      # ③ 服务舱 · 能源与热控
        (R, 32, 'green', 6.2),     # ④ 生态生保舱
        (R, 28, 'blue', 6.2),      # ⑤ 居住舱
        (R, 20, 'steel', 5.4),     # ⑥ AI 与指令舱
        (10.0, 12, 'gray', 4.0),   # ⑦ 节点与气闸
    ]
    y = 0.0
    tops = []
    for i, (r, h, c, tp) in enumerate(segs):
        g.cyl(0, y, 0, r, h, c, n=14, tex='seam', tp=tp)
        # 舱段之间的对接环：只在几个关键接缝上做，全做会吃掉一半面片预算
        if i in (1, 3, 5):
            g.ring(0, y - 1.6, 0, r + 0.6, r - 1.4, 3.0, 'steel', n=10, inner=False)
        if i in (2, 4):
            # 舱段外壁的一圈舷窗带（点阵），让「有人在里面」这件事看得见
            g.arc(0, y + h * 0.35, 0, r + 0.45, h * 0.3, 142, 218, 'amber',
                  n=5, tex='dot', tp=3.2)
        y += h + gap
        tops.append(y)
    g.dome(0, y, 0, R, 13, 'steel', n=12, segs=3, tex='seam', tp=5.4)    # 前端穹顶
    g.ring(0, y + 12.0, 0, 10.4, 8.0, 3.2, 'dark', n=10, inner=False)    # 对接口
    # 太阳能帆板 ×2（格栅 + 边框 + 根部铰链）
    for sx in (-1, 1):
        g.plate(sx * 34, tops[2] + 8, 0, 26, 34, 'blue2', t=1.5, tex='grid', tp=3.0)
        g.cyl(sx * 16.5, tops[2] + 6.4, 0, 1.6, 6, 'gray', n=5, axis='x',
              tex='seam', tp=2.4)
        g.cyl(sx * 30, tops[2] + 6.8, 0, 1.2, 22, 'gray', n=5, axis='x',
              tex='seam', tp=3)
    # 热辐射板：百叶纹理，挂在帆板上方避开重叠
    g.plate(0, tops[3] + 2, 30, 30, 18, 'gray', t=1.5, tex='slat', tp=3.2)
    g.cyl(0, tops[3] - 1, 21, 1.4, 9, 'gray', n=5, axis='z', tex='seam', tp=2.4)
    # 姿控推力器簇：四组，贴在服务舱一圈
    for i in range(4):
        a = math.radians(i * 90 + 45)
        g.cyl(R * math.sin(a), tops[1] + 6, R * math.cos(a), 1.7, 5, 'ink',
              n=5, tex='seam', tp=2)
    # 机械臂基座与备用工具挂点（收口页要回答「这些东西装在哪儿」）
    g.box(R - 0.6, tops[1] + 14, -3.4, 4.4, 6, 6.8, 'gray', tex='plate', tp=2.8)
    return tops


