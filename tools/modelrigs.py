"""十一个可旋转模型的几何数据：十个板块各一个，收口页多一个整船分解图。

**改模型只改这个文件**，渲染与自适配在 models3d.py 里。

两条硬规矩（改之前先看 models3d.py 开头的说明）：

1. **只写轴对齐的长方体与竖直圆柱。** y 向上、z 朝观察者。
   `box(x, y, z, w, h, d)` 的 (x, y, z) 是左下后角；`cyl(x, y0, z, r, h)` 的 y0 是底面高度。
2. **编号点要落在部件外面，而且同一列上的两个点高度至少差 22。**
   编号点是 2D 覆盖层，压在模型中间会看不出指向谁；高度差不够时，
   转到俯仰极限（rx=−52°）两者的屏幕间距会缩到 PIN_D 以下而被断言拦下。
"""

import math

from models3d import M3D, legend_html, HINT   # noqa: F401  （HINT 由 build.py 直接用）


# ================================================================ 01 可回收火箭
def scene_falcon():
    g = M3D('猎鹰 9 一级 · 可回收整级',
            '猎鹰 9 一级的可旋转模型：贮箱、栅格舵、着陆腿与九台梅林发动机')
    R = 12.0
    # 箭体三段筒体：环向焊缝（seam）是这类铝合金箭体最好认的一层细节，
    # 一张平面贴图就能把「一块光板」变成「一圈一圈焊起来的筒」。
    g.cyl(0, -14, 0, R, 50, 'steel', n=14, tex='seam', tp=12, segs=3)    # ① RP-1 贮箱
    g.cyl(0, 36, 0, R - 0.35, 8.5, 'gray', n=14, tex='rib', tp=4.2)     # ② 箱间段
    g.cyl(0, 44.5, 0, R, 51.5, 'steel', n=14, tex='seam', tp=12, segs=3)  # ③ 液氧贮箱
    g.cyl(0, 96, 0, R, 9, 'gray', n=14, tex='plate', tp=7)              # ④ 级间段
    g.ring(0, 105, 0, R + 0.7, R - 1.0, 2.2, 'dark', n=12, inner=False)  # ⑤ 顶部法兰
    # 贴着外壁的液氧输送管（真实箭体上很显眼的一条），放在 45° 方向避开四片舵
    g.cyl(8.5, -12, -8.5, 1.4, 108, 'gray', n=5, tex='seam', tp=5)       # ⑥ 输送管路
    g.cyl(-8.5, -12, 8.5, 1.1, 96, 'gray', n=5, tex='seam', tp=5)        # ⑦ 电缆护罩
    # 推力结构：外圈发动机就挂在这个筒段下面
    g.cyl(0, -30, 0, R - 0.6, 16, 'dark', n=14, tex='rib', tp=4.5)       # ⑧ 发动机段
    # 九台梅林：外圈八台 + 中心一台（中心那台可节流到 40%，是最后减速用的）
    for i in range(8):
        a = math.radians(i * 45 + 22.5)
        g.frustum(7.4 * math.sin(a), -47, 7.4 * math.cos(a), 3.3, 1.5, 17,
                  'ink', n=6, segs=1, cap_bot=False, tex='tube', tp=2.6)
    g.frustum(0, -50, 0, 4.2, 2.0, 20, 'ink', n=8, segs=2, cap_bot=False,
              tex='tube', tp=3.0)
    # 栅格舵 ×4：舵面沿**切向**展开、厚度沿径向，所以宽度和深度要跟着方位换，
    # 不能四个方向都用同一组尺寸（那样侧面的两片会变成薄纸片）。
    for i in range(4):
        a = math.radians(i * 90)
        sx, sz = math.sin(a), math.cos(a)
        tx, tz = math.cos(a), -math.sin(a)
        cx, cz = (R + 1.1) * sx, (R + 1.1) * sz
        w = 9.5 if i % 2 == 0 else 4.4      # 沿 x 的尺寸
        d = 4.4 if i % 2 == 0 else 9.5      # 沿 z 的尺寸
        g.box(cx - w / 2, 89, cz - d / 2, w, 8, d, 'dark', tex='grid', tp=2.4)
        # 舵机罩：贴在筒壁上的一小块，让舵看起来是「装上去的」而不是浮着
        g.box((R - 0.2) * sx - 2.2 * abs(tx) - 1.6 * abs(sx), 90.5,
              (R - 0.2) * sz - 2.2 * abs(tz) - 1.6 * abs(sz),
              3.2 * abs(sx) + 4.4 * abs(tx), 5, 3.2 * abs(sz) + 4.4 * abs(tz),
              'gray', tex='plate', tp=3)
    # 着陆腿 ×4：锥形主腿（下大上小）+ 脚垫 + 液压作动筒
    for i in range(4):
        a = math.radians(i * 90)
        sx, sz = math.sin(a), math.cos(a)
        lx, lz = (R + 1.7) * sx, (R + 1.7) * sz
        w, d = (5.6, 4.6) if i % 2 == 0 else (4.6, 5.6)
        g.taper(lx, -24, lz, w, d, 3.4, 3.4, 34, 'gray', tex='seam', tp=6)
        g.box((R + 1.7) * sx - 3.6 * sx - 3.4, -27, (R + 1.7) * sz - 3.6 * sz - 3.4,
              7, 3, 7, 'ink')
        g.box((R - 0.6) * sx - 1.5 * abs(sx) - 2.2 * abs(sz) * 0 + 0, -14,
              (R - 0.6) * sz - 1.5 * abs(sz), 3.0, 26, 3.0, 'dark', tex='seam', tp=4)
    # 级间段附近的 RCS 冷气推力器（两两一组）
    for (px, pz, w, d) in ((R - 0.4, -5, 3.4, 5.0), (-R + 0.4 - 3.4, -5, 3.4, 5.0)):
        g.box(px, 100, pz, w, 3.4, d, 'ink', tex='dot', tp=2.6)
    g.pin(1, 19, 101, 0, part=3)      # 级间段
    g.pin(2, 19, 62, 0, part=2)       # 液氧贮箱
    g.pin(3, -20, 93, 0, part=17)     # 栅格舵（第一片舵面）
    g.pin(4, -20, -16, 0, part=25)    # 着陆腿（第一条腿）
    g.pin(5, 19, -53, 0, part=16)     # 中心那台梅林
    return g



# ================================================================ 02 火箭技术
def scene_engine():
    g = M3D('全流量分级燃烧液氧甲烷发动机',
            '全流量分级燃烧发动机的可旋转模型：两台预燃室、两台涡轮泵与主燃烧室')
    # 喷管：钟形（分段圆台近似），tube 纹理就是再生冷却的管束——
    # 原先那根等径圆柱是整台机器最假的地方。
    g.frustum(0, -48, 0, 19.0, 7.6, 27, 'dark', n=14, segs=3, cap_bot=False,
              tex='tube', tp=2.4)                                       # ① 喷管扩张段
    g.ring(0, -49.5, 0, 19.8, 18.7, 2.6, 'steel', n=14, inner=False)     # 出口加强环
    g.frustum(0, -21, 0, 7.6, 8.6, 6, 'dark', n=14, segs=1,
              tex='tube', tp=2.6)                                       # ② 喉部
    g.cyl(0, -15, 0, 8.8, 31, 'steel', n=14, tex='seam', tp=4.2, segs=4)  # ③ 主燃烧室
    g.cyl(0, 16, 0, 10.0, 5.5, 'gray', n=14, tex='dot', tp=3.4)          # ④ 喷注器与顶盖
    for sgn in (-1, 1):
        tag = '氧' if sgn < 0 else '甲烷'
        g.cyl(sgn * 33, 21, 0, 8.0, 18, 'amber', n=10, tex='seam', tp=4.5)   # 预燃室
        g.dome(sgn * 33, 39, 0, 8.0, 7, 'amber', n=8, segs=2, tex='seam', tp=4)
        g.cyl(sgn * 55, -7, 0, 9.0, 18, 'blue2', n=10, tex='seam', tp=4.5)   # 涡轮泵
        g.dome(sgn * 55, 11, 0, 9.0, 7.5, 'blue2', n=8, segs=2, tex='seam', tp=4)
        # 泵—预燃室高压管路：三段小圆筒凑一根折管，比一根直筒像管路
        g.cyl(sgn * 44, 24, 0, 2.0, 12, 'gray', n=5, axis='x', tex='seam', tp=2.4)
        g.cyl(sgn * 44, 34, 0, 2.0, 11, 'gray', n=5, tex='seam', tp=2.4)
        g.cyl(sgn * 55, 18, 0, 2.6, 8, 'gray', n=5, tex='seam', tp=2.6)
        # 预燃室到喷注器的热燃气通道
        g.cyl(sgn * 24, 19, 0, 2.4, 12, 'gray', n=5, axis='x', tex='seam', tp=2.6)
        # 泵入口法兰
        g.ring(sgn * 55, -9, 0, 10.2, 8.2, 2.0, 'steel', n=8, inner=False)
        # 传感器与阀门（小件，但这一层的「密度感」全靠它们）
        g.cyl(sgn * 33, 6, 5.0, 1.3, 7, 'ink', n=4, tex='seam', tp=2)
        g.cyl(sgn * 46, 40, -5.0, 1.6, 5, 'red', n=4)
    # 喷管与燃烧室之间的冷却环带：贴在喉部外圈，让「先收后放」的形状看得见
    g.ring(0, -20, 0, 9.6, 8.6, 3.2, 'steel', n=12, inner=False, tex='rib', tp=3)
    g.pin(1, -46, 34, 0, part=5)      # 富氧预燃室
    g.pin(2, 46, 34, 0, part=16)      # 富燃预燃室
    g.pin(3, -70, 2, 0, part=7)       # 氧泵
    g.pin(4, 70, 2, 0, part=18)       # 甲烷泵
    g.pin(5, 0, 26, 22, part=4)       # 喷注器与顶盖
    g.pin(6, -22, -34, 0, part=0)     # 主燃烧室与喷管
    return g



# ================================================================ 03 星舰
def scene_starship():
    g = M3D('星舰组合体 · 助推级 + 飞船',
            '星舰组合体的可旋转模型：助推级贮箱、热分离环、飞船与四片气动翼')
    R = 14.0
    # 助推发动机段：33 台猛禽画成「外圈 8 + 中心 3」——再多也挤成一团噪点，
    # 而这个数量已经足够读出「一圈围着中心」的排布。
    g.cyl(0, 0, 0, R + 0.4, 16, 'dark', n=16, tex='rib', tp=5)          # ① 发动机段
    for i in range(8):
        a = math.radians(i * 45 + 22.5)
        g.frustum(11.4 * math.sin(a), -15, 11.4 * math.cos(a), 3.4, 1.7, 15,
                  'ink', n=6, segs=1, cap_bot=False, tex='tube', tp=2.6)
    for i in range(3):
        a = math.radians(i * 120 + 60)
        g.frustum(4.8 * math.sin(a), -13, 4.8 * math.cos(a), 3.0, 1.5, 13,
                  'ink', n=6, segs=1, cap_bot=False, tex='tube', tp=2.6)
    # 不锈钢箭体：环焊缝密集（不锈钢筒段本来就是一环一环焊起来的）
    g.cyl(0, 16, 0, R, 116, 'steel', n=14, tex='seam', tp=13, segs=4)    # ② 助推贮箱
    g.ring(0, 132, 0, R + 0.9, R - 1.4, 7, 'dark', n=12, inner=False,
           tex='rib', tp=3.6)                                          # ③ 热分离环
    g.cyl(0, 139, 0, R, 84, 'white', n=14, tex='seam', tp=13, segs=3)    # ④ 飞船体
    # 迎风面热盾瓦片区：只占圆周约 96°，用弧形贴片贴上去——
    # 用整圈圆柱去凑会把背风面也盖成黑的，一眼就假。
    # 热盾瓦片区：只覆盖迎风那一段（约 130°）。
    # ⚠️ 弧段中心要挑**看得见**的方向：默认视角是绕 y 转 −32°，
    # 模型空间里"正对镜头"的方位角是 +32°，所以中心取 85° 左右最合适。
    # 之前中心取 180°（正背面），结果整块热盾只在轮廓上露出一条黑边，
    # 花了十几个面片画的东西等于没画。
    # flat=True + jitter：瓦片本来就是一块块平的，给它平滑过渡反而不像瓦片；
    # 逐片微差让深浅不匀，这正是真实热盾的样子。
    g.arc(0, 141, 0, R + 0.55, 80, 20, 150, 'ink', n=11, tex='tile', tp=3.0,
          jitter=0.055, flat=True)
    g.dome(0, 223, 0, R, 24, 'white', n=12, segs=3, tex='seam', tp=6)   # ⑤ 鼻锥
    # 四片气动翼：梯形（四棱台），根部厚、翼尖薄，这才像翼面而不是砖
    for i in (0, 1):
        sgn = -1 if i == 0 else 1
        g.taper(sgn * 17.0, 194, -5, 4.6, 12, 3.0, 8.5, 24, 'dark',
                tex='seam', tp=6)                                     # ⑥ 前翼 ×2
        g.box(sgn * 15.2 - 2.6, 192, -7.0, 5.2, 8, 5.0, 'gray', tex='plate', tp=3)
        g.taper(sgn * 17.0, 148, -5, 4.6, 14, 3.0, 10.0, 28, 'dark',
                tex='seam', tp=6)                                     # ⑦ 后翼 ×2
        g.box(sgn * 15.2 - 2.6, 146, -8.0, 5.2, 8, 5.0, 'gray', tex='plate', tp=3)
    g.ring(0, 222, 0, 10.0, 7.6, 3.0, 'gray', n=10, inner=False)        # ⑧ 载荷舱口
    g.pin(1, 19, 206, 0, part=21)     # 前翼（指 +x 那一侧）
    g.pin(2, -19, 135, 0, part=13)    # 热分离环
    g.pin(3, 19, 76, 0, part=12)      # 助推贮箱
    g.pin(4, -19, -13, 0, part=0)     # 助推发动机段
    g.pin(5, 16, 178, 8, part=15)      # 迎风面热盾瓦片区（挪到弧段所在的方位上）
    return g



# ================================================================ 04 生态圈
def scene_biosphere():
    R = 14.0
    g = M3D('闭环生态生保舱段',
            '飞船生态圈的可旋转模型：服务舱、植物栽培舱、居住舱与节点舱')
    g.cyl(0, 0, 0, R, 22, 'gray', n=14, tex='plate', tp=7)             # ① 服务舱
    g.ring(0, 22, 0, R + 0.6, R - 1.2, 3.0, 'steel', n=12, inner=False)  # 对接环
    g.cyl(0, 25, 0, R, 30, 'green', n=14, tex='seam', tp=7)             # ② 栽培舱
    # 栽培舱的观察窗带：一圈亮点阵，一眼看出「里面有在长东西」
    g.arc(0, 33, 0, R + 0.45, 14, 138, 222, 'amber', n=6, tex='dot', tp=3.4)
    g.ring(0, 55, 0, R + 0.6, R - 1.2, 3.0, 'steel', n=12, inner=False)
    g.cyl(0, 58, 0, R, 28, 'blue', n=14, tex='seam', tp=7)              # ③ 居住舱
    g.arc(0, 66, 0, R + 0.45, 12, 150, 210, 'steel', n=5, tex='dot', tp=3.0)
    g.ring(0, 86, 0, R + 0.6, R - 1.2, 3.0, 'steel', n=12, inner=False)
    g.cyl(0, 89, 0, R, 16, 'steel', n=14, tex='plate', tp=7)            # ④ 节点与气闸
    g.dome(0, 105, 0, R, 11, 'steel', n=12, segs=3, tex='seam', tp=6)   # ⑤ 前端穹顶
    # 气闸舱门与对接口：节点舱侧面唯一一个「能出去」的地方
    g.cyl(0, 92, -(R + 2.4), 3.6, 10, 'gray', n=10, axis='z', tex='seam', tp=4)
    g.ring(0, 92, -(R + 5.2), 4.6, 3.2, 2.4, 'dark', n=10, inner=False)
    # 太阳能帆板 ×2：格栅纹理 + 根部的铰链与支架
    for sx in (-1, 1):
        g.plate(sx * 34, 78, 0, 26, 38, 'blue2', t=1.5, tex='grid', tp=3.0)
        g.cyl(sx * 15.5, 76, 0, 1.6, 6, 'gray', n=5, axis='x', tex='seam', tp=2.4)
        g.cyl(sx * 30, 76.5, 0, 1.2, 22, 'gray', n=5, axis='x', tex='seam', tp=3)
    # 热辐射板：百叶纹理；挂在帆板下方，避免和帆板叠在一起
    # ⑥ 热辐射板：挂到中段（栽培舱高度）而不是顶部——顶部左右各有一块帆板，
    # 放在 y=88 会和它们在同一屏位置叠起来，两条板子糊成一块。
    g.plate(0, 41, 30, 30, 18, 'gray', t=1.5, tex='slat', tp=3.2)
    g.cyl(0, 39, 21, 1.4, 9, 'gray', n=5, axis='z', tex='seam', tp=2.4)
    # 侧壁的推力器簇与天线
    for i in range(4):
        a = math.radians(i * 90 + 45)
        g.cyl(R * math.sin(a), 6, R * math.cos(a), 1.6, 5, 'ink', n=5,
              tex='seam', tp=2)                                        # ⑦ 姿控推力器 ×4
    g.pin(1, 19, 96, 0, part=8)       # 节点与气闸
    g.pin(2, 19, 70, 0, part=5)       # 居住舱
    g.pin(3, 19, 40, 0, part=2)       # 植物栽培舱
    g.pin(4, 19, 8, 0, part=0)        # 服务舱
    g.pin(5, -20, 84, 0, part=12)     # 太阳能帆板
    return g



# ================================================================ 05 光速推进
def scene_lightsail():
    g = M3D('光帆飞船 · 四片帆与帆桁',
            '光帆飞船的可旋转模型：四片光帆、十字帆桁、载荷舱与姿控推进')
    # 四片帆面：金色聚酰亚胺，格纹是帆面的拼接缝（真实的帆就是一大片一大片拼的）
    for sx in (-1, 1):
        for sz in (-1, 1):
            # 每片帆用**浅锥台**而不是平板：四片共面时会读成一整块金板，
            # 鼓起 3 个单位之后才有"四片独立帆"的样子——这也正是真实的帆在
            # 光压下的形状（中心被推得鼓起来）。
            g.taper(sx * 24 - 22, 12, sz * 24 - 22, 44, 44, 10, 10, 3.0,
                    'gold', tex='grid', tp=4.5)
            # 帆的外缘加强条：帆边上那道折边，是分辨「一片帆」与「一块金板」的关键
            g.box(sx * 46 - 0.9 * (sx > 0) - 0.0, 11.4, sz * 24 - 22, 1.8, 2.4, 44,
                  'amber', tex='seam', tp=3)
    # 帆桁：十字承力框，每根用「箱形主梁 + 两道斜撑」表达桁架感
    for sz in (-1, 1):
        g.box(-50, 8.6, sz * 1.6 - 0.8, 100, 3.4, 3.4, 'gray', tex='plate', tp=5)
    for sx in (-1, 1):
        g.box(sx * 1.6 - 0.8, 8.6, -50, 3.4, 3.4, 100, 'gray', tex='plate', tp=5)
    for sx in (-1, 1):
        for sz in (-1, 1):
            # 斜撑：从帆桁根部斜拉到帆角，没有它就只是一块吊着的板子
            # 斜撑要落在帆面**下面**：立在帆上会变成四根小柱子，
            # 看着像装饰而不是承力件
            g.box(sx * 26 - 1.1, 9.6, sz * 26 - 1.1, 2.2, 2.2, 2.2, 'gray')
            g.taper(sx * 30, 5.0, sz * 30, 1.6, 1.6, 3.6, 3.6, 7, 'gray')
            g.box(sx * 42 - 2.4, 11.0, sz * 42 - 2.4, 4.8, 1.6, 4.8, 'steel')
    # 载荷舱：本体 + 顶部穹顶 + 通信喇叭 + 相机
    g.box(-7, -12, -7, 14, 21, 14, 'steel', tex='plate', tp=4.5)         # ① 载荷舱
    g.dome(0, 9, 0, 6.6, 5, 'steel', n=10, segs=2, tex='seam', tp=3.5)
    g.frustum(0, 14, 0, 2.4, 5.6, 7, 'gray', n=10, segs=2, tex='seam', tp=3)
    g.cyl(4.6, -3, 7.6, 1.5, 5, 'ink', n=6, axis='z', tex='seam', tp=2.2)
