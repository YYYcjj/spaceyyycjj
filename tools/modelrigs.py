"""十一个可旋转模型的几何数据：十个板块各一个，收口页多一个整船分解图。

**改模型只改这个文件**，渲染与自适配在 models3d.py 里。

两条硬规矩（改之前先看 models3d.py 开头的说明）：

1. **只写轴对齐的长方体与竖直圆柱。** y 向上、z 朝观察者。
   `box(x, y, z, w, h, d)` 的 (x, y, z) 是左下后角；`cyl(x, y0, z, r, h)` 的 y0 是底面高度。
2. **编号点要落在部件外面，而且同一列上的两个点高度至少差 22。**
   编号点是 2D 覆盖层，压在模型中间会看不出指向谁；高度差不够时，
   转到俯仰极限（rx=−52°）两者的屏幕间距会缩到 PIN_D 以下而被断言拦下。
"""

